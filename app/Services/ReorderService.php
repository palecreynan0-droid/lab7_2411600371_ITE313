<?php

namespace App\Services;

use App\Models\Product;
use App\Models\PurchaseOrder;
use App\Models\PurchaseOrderItem;
use App\Models\User;
use Illuminate\Support\Collection;
use Illuminate\Support\Facades\DB;

class ReorderService
{
    public const USAGE_DAYS = 30;     // history window for average usage
    public const COVERAGE_DAYS = 30;  // how many days of stock each order should cover
    public const DEFAULT_LEAD_TIME = 7;

    public function averageDailyUsage(Product $product): float
    {
        $out = $product->inventoryTransactions()
            ->where('type', 'out')
            ->where('created_at', '>=', now()->subDays(self::USAGE_DAYS))
            ->sum('quantity');

        return $out / self::USAGE_DAYS;
    }

    protected function leadTime(Product $product): int
    {
        return $product->supplier?->lead_time_days ?? self::DEFAULT_LEAD_TIME;
    }

    /** Units already on open purchase orders but not yet received. */
    public function quantityOnOrder(Product $product): int
    {
        return (int) PurchaseOrderItem::where('product_id', $product->id)
            ->whereHas('purchaseOrder', fn ($q) => $q->whereIn('status', ['draft', 'pending', 'approved', 'sent']))
            ->selectRaw('COALESCE(SUM(quantity - received_quantity), 0) as total')
            ->value('total');
    }

    // Reorder Point = (Average Daily Usage × Lead Time) + Safety Stock
    public function calculateReorderPoint(Product $product): int
    {
        $calculated = (int) ceil($this->averageDailyUsage($product) * $this->leadTime($product))
            + $product->safety_stock;

        // With no sales history the formula gives 0, so never go below the manual level.
        return max($calculated, $product->reorder_level);
    }

    public function calculateOptimalOrderQuantity(Product $product): int
    {
        $reorderPoint = $this->calculateReorderPoint($product);
        $usage = $this->averageDailyUsage($product);

        $target = (int) ceil($usage * ($this->leadTime($product) + self::COVERAGE_DAYS))
            + $product->safety_stock;

        if ($target <= $reorderPoint) {
            $target = $reorderPoint * 2; // sensible fallback when there is little history
        }

        $needed = max(1, $target - ($product->quantity + $this->quantityOnOrder($product)));

        // Round up to whole packages
        $package = max(1, $product->package_size);

        return (int) (ceil($needed / $package) * $package);
    }

    public function getProductsNeedingReorder(): Collection
    {
        return Product::with('supplier')
            ->whereHas('supplier', fn ($q) => $q->active())
            ->get()
            ->filter(fn (Product $p) =>
                ($p->quantity + $this->quantityOnOrder($p)) <= $this->calculateReorderPoint($p))
            ->values();
    }

    public function groupProductsBySupplier(Collection $products): Collection
    {
        return $products->groupBy('supplier_id');
    }

    /** Creates one draft PO per supplier. Returns the created orders. */
    public function generatePurchaseOrders(): Collection
    {
        $creator = User::where('role', 'admin')->first();
        if (! $creator) {
            throw new \RuntimeException('No admin user found to own generated purchase orders.');
        }

        $created = collect();

        foreach ($this->groupProductsBySupplier($this->getProductsNeedingReorder()) as $products) {
            $supplier = $products->first()->supplier;

            $po = DB::transaction(function () use ($products, $supplier, $creator) {
                $po = PurchaseOrder::create([
                    'reference_number' => PurchaseOrder::generateReferenceNumber(),
                    'supplier_id' => $supplier->id,
                    'status' => 'draft',
                    'order_date' => now()->toDateString(),
                    'expected_delivery_date' => now()->addDays($supplier->lead_time_days)->toDateString(),
                    'notes' => 'Auto-generated by reorder check.',
                    'created_by' => $creator->id,
                ]);

                $po->items()->createMany($products->map(fn (Product $p) => [
                    'product_id' => $p->id,
                    'quantity' => $this->calculateOptimalOrderQuantity($p),
                    'unit_price' => $p->price,
                ])->all());

                $po->load('items')->calculateTotal();

                if ($po->total < $supplier->minimum_order_amount) {
                    $po->update(['notes' => $po->notes . ' Below supplier minimum order of ₱'
                        . number_format($supplier->minimum_order_amount, 2) . '.']);
                }

                return $po;
            });

            $created->push($po);
        }

        return $created;
    }
}